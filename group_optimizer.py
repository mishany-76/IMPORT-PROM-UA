import re

def normalize_catalog_structure(merged_products_df, groups_cols):
    """
    Формирует строгое 3-уровневое дерево категорий:
    L1: Корневой раздел (Жіночий одяг, Чоловічий одяг, Взуття, Сумки та рюкзаки, Футбольне екіпірування, Трендові товари)
    L2: Тип товара (Сукні, Футболки, Кросівки тощо)
    L3: Конечная группа с логистическим суффиксом:
        - (Нова Пошта / Укрпошта) для AGER
        - (Тільки Нова Пошта) для остальных (IZIDROP, MOYDROP, KIRS, BAGSROOM, FOOTBALLERS)
    """
    
    # Справочник маппинга L2 -> L1
    L2_RULES = [
        # Взуття
        (r'кросівк|кед|кроссовк|снікерс', 'Кросівки та кеди', 'Взуття'),
        (r'черевик|ботинк|ботильон|берц', 'Черевики та ботильйони', 'Взуття'),
        (r'туфл|лофер|мокасин|оксфорд|балетки', 'Туфлі та мокасини', 'Взуття'),
        (r'чобот|сапог|угг|унт', 'Чоботи та напівчоботи', 'Взуття'),
        (r'босоніжк|сандал|шльоп|сланц|шлеп|вьетнамк', 'Босоніжки та сандалі', 'Взуття'),
        (r'тапочки|капці', 'Домашнє взуття', 'Взуття'),
        (r'взуття|обувь', 'Взуття (інше)', 'Взуття'),

        # Сумки та галантерея
        (r'рюкзак|ранец', 'Рюкзаки та ранці', 'Сумки, рюкзаки та аксесуари'),
        (r'сумк|шопер|клатч|бананка|мессенджер', 'Сумки та клатчі', 'Сумки, рюкзаки та аксесуари'),
        (r'гаманець|кошелек|портмоне|визитниц|картхолдер', 'Гаманці та портмоне', 'Сумки, рюкзаки та аксесуари'),
        (r'ремін|пояс|ремень', 'Ремені та пояси', 'Сумки, рюкзаки та аксесуари'),
        (r'валіза|чемодан|дорожн', 'Дорожні сумки та валізи', 'Сумки, рюкзаки та аксесуари'),
        (r'парасоль|зонт', 'Парасолі', 'Сумки, рюкзаки та аксесуари'),

        # Футбольна та спортивна екіпіровка
        (r'бутс|сороконожк|футзал|копочки', 'Футбольне взуття (бутси)', 'Футбольне та спортивне екіпірування'),
        (r'форма|гетр|щитк|воротар|перчатк.*вратар', 'Футбольна екіпіровка', 'Футбольне та спортивне екіпірування'),
        (r'м\'яч|мяч', 'Спортивні м\'ячі', 'Футбольне та спортивне екіпірування'),

        # Жіночий одяг
        (r'сукн|плать|сарафан', 'Сукні та сарафани', 'Жіночий одяг'),
        (r'спідниц|юбк', 'Спідниці', 'Жіночий одяг'),
        (r'блуз|тунік', 'Блузи та туніки', 'Жіночий одяг'),
        (r'боді|комбідрес', 'Боді та комбідреси', 'Жіночий одяг'),
        (r'купальник|плавк.*жіноч', 'Купальники та пляжний одяг', 'Жіночий одяг'),
        (r'бюстгальтер|трусик|білизн.*жіноч|пеньюар|нічн', 'Жіноча спідня білизна', 'Жіночий одяг'),

        # Одяг спільний/роздільний
        (r'костюм', 'Костюми та комплекти', 'Одяг'),
        (r'куртк|пуховик|пальто|парк|вітрівк|жилет', 'Верхній одяг', 'Одяг'),
        (r'джинс', 'Джинси', 'Одяг'),
        (r'штани|брюк|легінс|лосин|джогер|лосины', 'Штани та брюки', 'Одяг'),
        (r'худі|толстовк|світшот|батник|кенгуру', 'Худі, світшоти та толстовки', 'Одяг'),
        (r'кофт|кардиган|светр|джемпер|водолазк|гольф', 'Кофти, светри та кардигани', 'Одяг'),
        (r'футболк|поло|майк', 'Футболки, майки та поло', 'Одяг'),
        (r'сорочк|рубашк', 'Сорочки', 'Одяг'),
        (r'шорт|бридж', 'Шорти та бриджі', 'Одяг'),
        (r'піжам|халат|домашн.*одяг', 'Домашній одяг та піжами', 'Одяг'),
        (r'термобілизн', 'Термобілизна', 'Одяг'),
        (r'шкарпетк|носк|колгот', 'Шкарпетки та панчохи', 'Одяг'),
        (r'шапк|шарф|рукавичк|кепк|бейсболк', 'Головні убори та аксесуари', 'Одяг'),

        # Трендові товари та техніка
        (r'навушник|колонк|акустик|гарнітур', 'Аудіотехніка та навушники', 'Трендові товари та техніка'),
        (r'смарт.*годинник|фітнес|smart.*watch', 'Смарт-годинники та гаджети', 'Трендові товари та техніка'),
        (r'ліхтар|лампа|нічник|освітлен', 'Освітлення та ліхтарі', 'Трендові товари та техніка'),
        (r'повербанк|зарядн|кабель', 'Мобільні аксесуари та живлення', 'Трендові товари та техніка'),
        (r'іграшк|конструктор|дитяч', 'Дитячі товари та іграшки', 'Трендові товари та техніка'),
        (r'крас|макіяж|манікюр|косметик|догляд|фен|стайлер', 'Товари для краси та здоров\'я', 'Трендові товари та техніка'),
        (r'кухн|посуд|дім|прибирання|декор', 'Товари для дому та кухні', 'Трендові товари та техніка')
    ]

    def classify(row):
        supp = str(row.get('Особисті_нотатки', '')).strip().upper()
        name = str(row.get('Назва_позиції', '')).lower() + ' ' + str(row.get('Назва_позиції_укр', '')).lower()
        old_grp = str(row.get('Назва_групи', '')).lower()
        text = f"{name} {old_grp}"

        # Логистический суффикс
        if supp == 'AGER':
            logistics_suffix = "(Нова Пошта / Укрпошта)"
        else:
            logistics_suffix = "(Тільки Нова Пошта)"

        # Специфика поставщика FOOTBALLERS
        if supp == 'FOOTBALLERS' or 'бутс' in text or 'м\'яч' in text or 'гетр' in text or 'щитк' in text:
            l1 = "Футбольне та спортивне екіпірування"
            for pat, l2_name, _ in L2_RULES:
                if re.search(pat, text):
                    l2 = l2_name
                    break
            else:
                l2 = "Спортивні аксесуари та форма"
            l3 = f"{l2} {logistics_suffix}"
            return l1, l2, l3

        # Определение L2 и базового L1
        target_l1 = None
        target_l2 = None
        for pat, l2_name, l1_cand in L2_RULES:
            if re.search(pat, text):
                target_l2 = l2_name
                target_l1 = l1_cand
                break

        if not target_l2:
            if any(k in text for k in ['сумк', 'рюкзак', 'гаманець', 'пояс']):
                target_l1 = "Сумки, рюкзаки та аксесуари"
                target_l2 = "Аксесуари та шкіргалантерея"
            elif any(k in text for k in ['взутт', 'крос', 'туфл', 'ботинк', 'сапог', 'слан']):
                target_l1 = "Взуття"
                target_l2 = "Взуття (інше)"
            else:
                target_l1 = "Одяг"
                target_l2 = "Повсякденний одяг"

        # Уточнение пола для категории 'Одяг'
        if target_l1 == 'Одяг':
            is_men = any(k in text for k in ['чоловіч', 'мужск', 'для чоловіків', 'для мужчин', 'хлопч'])
            is_women = any(k in text for k in ['жіноч', 'женск', 'для жінок', 'для женщин', 'дівчат'])
            if is_men and not is_women:
                target_l1 = "Чоловічий одяг"
            elif is_women and not is_men:
                target_l1 = "Жіночий одяг"
            else:
                if any(k in text for k in ['плать', 'сукн', 'блуз', 'спідниц', 'юбк', 'сарафан', 'купальник']):
                    target_l1 = "Жіночий одяг"
                else:
                    target_l1 = "Жіночий одяг" # Дефолт для неоднозначной одежды

        l3 = f"{target_l2} {logistics_suffix}"
        return target_l1, target_l2, l3

    # Классификация каждого товара
    l1_list, l2_list, l3_list = [], [], []
    for _, row in merged_products_df.iterrows():
        c_l1, c_l2, c_l3 = classify(row)
        l1_list.append(c_l1)
        l2_list.append(c_l2)
        l3_list.append(c_l3)

    # Генерация детерминированных ID
    # L1: 10001..
    # L2: 20001..
    # L3: 30001..
    l1_ids = {}
    l2_ids = {}
    l3_ids = {}
    
    unique_l1 = sorted(list(set(l1_list)))
    for idx, name in enumerate(unique_l1, start=10001):
        l1_ids[name] = str(idx)

    unique_l2 = sorted(list(set(zip(l1_list, l2_list))))
    for idx, (p_l1, name) in enumerate(unique_l2, start=20001):
        l2_ids[(p_l1, name)] = str(idx)

    unique_l3 = sorted(list(set(zip(l1_list, l2_list, l3_list))))
    for idx, (p_l1, p_l2, name) in enumerate(unique_l3, start=30001):
        l3_ids[(p_l1, p_l2, name)] = str(idx)

    # Обновляем товары: привязываем к L3 (конечная группа каталога)
    new_group_ids = []
    new_group_names = []
    for c_l1, c_l2, c_l3 in zip(l1_list, l2_list, l3_list):
        gid = l3_ids[(c_l1, c_l2, c_l3)]
        new_group_ids.append(gid)
        new_group_names.append(c_l3)

    merged_products_df['Номер_групи'] = new_group_ids
    merged_products_df['Ідентифікатор_групи'] = new_group_ids
    merged_products_df['Назва_групи'] = new_group_names

    # Собираем чистое дерево групп для листа Export Groups Sheet
    # ВАЖНО: берем ТОЛЬКО те группы, в которых физически есть реальные товары
    active_l3_tuples = set(zip(l1_list, l2_list, l3_list))
    active_l2_tuples = set((c_l1, c_l2) for c_l1, c_l2, _ in active_l3_tuples)
    active_l1_names = set(c_l1 for c_l1, _ in active_l2_tuples)

    groups_rows = []

    # Уровень 1 (только с товарами)
    for name, gid in l1_ids.items():
        if name not in active_l1_names:
            continue
        row = {c: '' for c in groups_cols}
        row['Номер_групи'] = gid
        row['Ідентифікатор_групи'] = gid
        row['Назва_групи'] = name
        row['Назва_групи_укр'] = name
        row['Номер_батьківської_групи'] = ''
        row['Ідентифікатор_батьківської_групи'] = ''
        groups_rows.append(row)

    # Уровень 2 (только с товарами)
    for (p_l1, name), gid in l2_ids.items():
        if (p_l1, name) not in active_l2_tuples:
            continue
        row = {c: '' for c in groups_cols}
        row['Номер_групи'] = gid
        row['Ідентифікатор_групи'] = gid
        row['Назва_групи'] = name
        row['Назва_групи_укр'] = name
        p_id = l1_ids[p_l1]
        row['Номер_батьківської_групи'] = p_id
        row['Ідентифікатор_батьківської_групи'] = p_id
        groups_rows.append(row)

    # Уровень 3 (только с товарами)
    for (p_l1, p_l2, name), gid in l3_ids.items():
        if (p_l1, p_l2, name) not in active_l3_tuples:
            continue
        row = {c: '' for c in groups_cols}
        row['Номер_групи'] = gid
        row['Ідентифікатор_групи'] = gid
        row['Назва_групи'] = name
        row['Назва_групи_укр'] = name
        p_id = l2_ids[(p_l1, p_l2)]
        row['Номер_батьківської_групи'] = p_id
        row['Ідентифікатор_батьківської_групи'] = p_id
        groups_rows.append(row)

    import pandas as pd
    optimized_groups_df = pd.DataFrame(groups_rows, columns=groups_cols)
    return merged_products_df, optimized_groups_df

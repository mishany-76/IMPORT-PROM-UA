def classify_row(row):
    """
    Классифицирует одну строку товара на L1, L2, L3 с учетом RU/UKR и логистики.
    """
    supp = str(row.get('Особисті_нотатки', '')).strip().upper()
    data_src = str(row.get('Джерело_даних', '')).lower()
    name_ru = str(row.get('Назва_позиції', ''))
    name_uk = str(row.get('Назва_позиції_укр', ''))
    old_grp = str(row.get('Назва_групи', ''))
    text = f"{name_ru} {name_uk} {old_grp}".lower()

    # Логистика: только AGER шлет Укрпочтой
    if supp == 'AGER' or 'ager' in data_src:
        suffix_ru = "(Новая Почта / Укрпочта)"
        suffix_uk = "(Нова Пошта / Укрпошта)"
    else:
        suffix_ru = "(Только Новая Почта)"
        suffix_uk = "(Тільки Нова Пошта)"

    # Поиск по правилам
    matched = None
    for key, l1_ru, l1_uk, l2_ru, l2_uk, pattern in CATALOG_RULES:
        if re.search(pattern, text):
            matched = (l1_ru, l1_uk, l2_ru, l2_uk)
            break

    # Fallback, если специфичное правило не сработало
    if not matched:
        if any(k in text for k in ['взутт', 'обув', 'черевик', 'ботинк', 'крос', 'кед', 'слан', 'шлеп', 'сандал']):
            matched = ("Обувь", "Взуття", "Кроссовки", "Кросівки")
        elif any(k in text for k in ['сумк', 'рюкзак', 'гаманець', 'кошелек', 'пояс', 'ремень']):
            matched = ("Сумки, рюкзаки и аксессуары", "Сумки, рюкзаки та аксесуари", "Сумки", "Сумки")
        elif supp == 'FOOTBALLERS':
            matched = ("Футбольное экипирование", "Футбольне екіпірування", "Футбольні мʼячі (Не бренд)", "Футбольні мʼячі (Не бренд)")
        elif supp == 'BAGSROOM':
            matched = ("Сумки, рюкзаки и аксессуары", "Сумки, рюкзаки та аксесуари", "Сумки", "Сумки")
        else:
            # По умолчанию обувь (основной ассортимент)
            matched = ("Обувь", "Взуття", "Кроссовки", "Кросівки")

    l1_ru, l1_uk, l2_ru, l2_uk = matched
    l3_ru = f"{l2_ru} {suffix_ru}"
    l3_uk = f"{l2_uk} {suffix_uk}"

    return {
        'l1_ru': l1_ru, 'l1_uk': l1_uk,
        'l2_ru': l2_ru, 'l2_uk': l2_uk,
        'l3_ru': l3_ru, 'l3_uk': l3_uk
    }


def normalize_catalog_structure(merged_products_df, groups_cols):
    """
    Нормализует привязку товаров и формирует чистое дерево групп.
    """
    logging.info(f"Начало нормализации каталога для {len(merged_products_df)} товаров...")

    classifications = []
    for _, row in merged_products_df.iterrows():
        classifications.append(classify_row(row))

    # Сбор уникальных групп для дерева
    # L1: ключ (l1_ru, l1_uk)
    # L2: ключ (l1_ru, l2_ru, l2_uk)
    # L3: ключ (l2_ru, l3_ru, l3_uk)

    l1_set = sorted(list(set((c['l1_ru'], c['l1_uk']) for c in classifications)))
    l1_ids = {}
    for idx, (l1_ru, l1_uk) in enumerate(l1_set, start=10001):
        l1_ids[(l1_ru, l1_uk)] = str(idx)

    l2_set = sorted(list(set((c['l1_ru'], c['l1_uk'], c['l2_ru'], c['l2_uk']) for c in classifications)))
    l2_ids = {}
    for idx, (l1_ru, l1_uk, l2_ru, l2_uk) in enumerate(l2_set, start=20001):
        l2_ids[(l1_ru, l1_uk, l2_ru, l2_uk)] = str(idx)

    l3_set = sorted(list(set((c['l1_ru'], c['l1_uk'], c['l2_ru'], c['l2_uk'], c['l3_ru'], c['l3_uk']) for c in classifications)))
    l3_ids = {}
    for idx, (l1_ru, l1_uk, l2_ru, l2_uk, l3_ru, l3_uk) in enumerate(l3_set, start=30001):
        l3_ids[(l1_ru, l1_uk, l2_ru, l2_uk, l3_ru, l3_uk)] = str(idx)

    # Привязываем товары строго к L3
    prod_group_ids = []
    prod_group_names = []
    for c in classifications:
        key3 = (c['l1_ru'], c['l1_uk'], c['l2_ru'], c['l2_uk'], c['l3_ru'], c['l3_uk'])
        gid = l3_ids[key3]
        prod_group_ids.append(gid)
        # В товаре Назва_групи на русском (по стандарту Prom)
        prod_group_names.append(c['l3_ru'])

    merged_products_df['Номер_групи'] = prod_group_ids
    merged_products_df['Ідентифікатор_групи'] = prod_group_ids
    merged_products_df['Назва_групи'] = prod_group_names

    # Формируем строки для Export Groups Sheet
    groups_rows = []

    # Уровень 1 (Корневой)
    for (l1_ru, l1_uk), gid in l1_ids.items():
        row = {col: '' for col in groups_cols}
        row['Номер_групи'] = gid
        row['Ідентифікатор_групи'] = gid
        row['Назва_групи'] = l1_ru
        row['Назва_групи_укр'] = l1_uk
        row['Номер_батьківської_групи'] = ''
        row['Ідентифікатор_батьківської_групи'] = ''
        groups_rows.append(row)

    # Уровень 2 (Категория)
    for (l1_ru, l1_uk, l2_ru, l2_uk), gid in l2_ids.items():
        row = {col: '' for col in groups_cols}
        row['Номер_групи'] = gid
        row['Ідентифікатор_групи'] = gid
        row['Назва_групи'] = l2_ru
        row['Назва_групи_укр'] = l2_uk
        row['Номер_батьківської_групи'] = l1_ids[(l1_ru, l1_uk)]
        row['Ідентифікатор_батьківської_групи'] = l1_ids[(l1_ru, l1_uk)]
        groups_rows.append(row)

    # Уровень 3 (Конечная с доставкой)
    for (l1_ru, l1_uk, l2_ru, l2_uk, l3_ru, l3_uk), gid in l3_ids.items():
        row = {col: '' for col in groups_cols}
        row['Номер_групи'] = gid
        row['Ідентифікатор_групи'] = gid
        row['Назва_групи'] = l3_ru
        row['Назва_групи_укр'] = l3_uk
        row['Номер_батьківської_групи'] = l2_ids[(l1_ru, l1_uk, l2_ru, l2_uk)]
        row['Ідентифікатор_батьківської_групи'] = l2_ids[(l1_ru, l1_uk, l2_ru, l2_uk)]
        groups_rows.append(row)

    optimized_groups_df = pd.DataFrame(groups_rows, columns=groups_cols)
    logging.info(f"Каталог сформирован: {len(l1_set)} L1, {len(l2_set)} L2, {len(l3_set)} L3 (всего {len(optimized_groups_df)} строк групп).")

    return merged_products_df, optimized_groups_df
